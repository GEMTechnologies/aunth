const path = require('path');
const HtmlWebpackPlugin = require('html-webpack-plugin');

module.exports = {
  mode: 'development',
  entry: './src/index.tsx',
  output: {
    path: path.resolve(__dirname, 'dist'),
    // CONTENT-HASHED, and that is a deployment correctness fix rather than a caching nicety.
    //
    // The bundle used to be a fixed `bundle.js`, served by nginx behind Cloudflare with
    // `cache-control: public, max-age=14400`. Measured on 2026-10-17: a freshly deployed bundle was
    // on disk at 414,257 bytes while the public URL still returned the previous 406,797-byte build
    // with `cf-cache-status: HIT, age: 242`. So an operator would load the old UI for up to four
    // hours after a release and conclude the deploy had failed - and there is no Cloudflare API
    // token here to purge with.
    //
    // A hashed filename gives every release its own URL, so the edge can cache aggressively and can
    // never serve a stale build. index.html is generated by HtmlWebpackPlugin and picks the name up
    // automatically.
    filename: '[name].[contenthash:8].js',
    // The old `bundle.js` files are removed, so the served directory does not grow one stale copy
    // per deploy.
    clean: true,
    publicPath: '/',
  },
  resolve: {
    extensions: ['.tsx', '.ts', '.js', '.jsx'],
  },
  module: {
    rules: [
      {
        test: /\.(ts|tsx)$/,
        use: 'ts-loader',
        exclude: /node_modules/,
      },
      {
        test: /\.css$/,
        use: ['style-loader', 'css-loader', 'postcss-loader'],
      },
      {
        test: /\.(png|svg|jpg|jpeg|gif)$/i,
        type: 'asset/resource',
      },
    ],
  },
  plugins: [
    new HtmlWebpackPlugin({
      template: './public/index.html',
    }),
  ],
  devServer: {
    static: {
      directory: path.join(__dirname, 'public'),
    },
    compress: true,
    port: 3001,
    host: '0.0.0.0',
    open: false,
    historyApiFallback: true,
    allowedHosts: 'all',
  },
};